"""projio sync writes native Claude Code skills (docs/specs/agent-interface-layers.md)."""
from __future__ import annotations

import json
from pathlib import Path

from projio import sync as sync_mod


def _skill(dir_: Path, name: str, desc: str) -> Path:
    d = dir_ / name
    d.mkdir(parents=True)
    (d / "SKILL.md").write_text(f"---\nname: {name}\ndescription: >\n  {desc}\n---\n\n# {name}\n\nBody.\n")
    (d / "notes.md").write_text("extra file\n")
    return d / "SKILL.md"


def test_sync_writes_native_skills_and_leaves_project_ones(tmp_path, monkeypatch):
    src = tmp_path / "pkg"
    a = _skill(src, "alpha", "Do alpha things. Use when alpha is asked.")
    b = _skill(src, "beta", "Do beta. Use for beta.")
    skills = [{"name": "alpha", "path": str(a), "source": "package:x"},
              {"name": "beta", "path": str(b), "source": "bundled"}]
    monkeypatch.setattr("projio.mcp.context._discover_skills", lambda root: list(skills))
    own = tmp_path / ".claude" / "skills" / "beta"
    own.mkdir(parents=True)
    (own / "SKILL.md").write_text("---\nname: beta\ndescription: the project's own\n---\n")
    cmds = tmp_path / ".claude" / "commands"
    cmds.mkdir()
    (cmds / "alpha.md").write_text(sync_mod._CLAUDE_CMD_HEADER + "\nLoad the projio skill **alpha**\n")
    (cmds / "mine.md").write_text("a command the user wrote\n")

    res = sync_mod._sync_claude_skills(tmp_path)
    out = tmp_path / ".claude" / "skills" / "alpha"
    text = (out / "SKILL.md").read_text()
    assert text.startswith("---\nname: alpha\ndescription: >\n  Do alpha things.")          # frontmatter first
    assert "projio:skill-sync: generated by `projio sync`" in text and "# alpha" in text
    assert (out / "notes.md").is_file() and (out / ".gitignore").read_text() == "*\n"
    assert json.loads((out / ".projio-skill").read_text())["origin"] == "package:x"
    assert (own / "SKILL.md").read_text().endswith("the project's own\n---\n")             # untouched
    assert res["written"] == ["alpha"] and res["kept"] == ["beta"]
    assert res["commands_removed"] == ["alpha"] and (cmds / "mine.md").is_file()

    assert sync_mod._sync_claude_skills(tmp_path)["action"] == "skipped"                   # up to date
    a.write_text(a.read_text().replace("Body.", "Body, changed."))
    assert sync_mod._sync_claude_skills(tmp_path)["written"] == ["alpha"]
    skills.pop(0)
    res = sync_mod._sync_claude_skills(tmp_path)
    assert res["removed"] == ["alpha"] and not out.exists()
