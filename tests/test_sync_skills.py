"""projio sync writes native Claude Code skills (docs/specs/agent-interface-layers.md)."""
from __future__ import annotations

import json
import os
import stat
from pathlib import Path

from projio import sync as sync_mod


def _skill(dir_: Path, name: str, desc: str) -> Path:
    d = dir_ / name
    d.mkdir(parents=True)
    (d / "SKILL.md").write_text(f"---\nname: {name}\ndescription: >\n  {desc}\n---\n\n# {name}\n\nBody.\n")
    (d / "notes.md").write_text("extra file\n")
    return d / "SKILL.md"


def test_sync_writes_native_skills_and_leaves_project_ones(tmp_path, monkeypatch):
    src = tmp_path / "pkg"
    a = _skill(src, "alpha", "Do alpha things. Use when alpha is asked.")
    b = _skill(src, "beta", "Do beta. Use for beta.")
    skills = [{"name": "alpha", "path": str(a), "source": "package:x"},
              {"name": "beta", "path": str(b), "source": "bundled"}]
    monkeypatch.setattr("projio.mcp.context._discover_skills", lambda root: list(skills))
    own = tmp_path / ".claude" / "skills" / "beta"
    own.mkdir(parents=True)
    (own / "SKILL.md").write_text("---\nname: beta\ndescription: the project's own\n---\n")
    cmds = tmp_path / ".claude" / "commands"
    cmds.mkdir()
    (cmds / "alpha.md").write_text(sync_mod._CLAUDE_CMD_HEADER + "\nLoad the projio skill **alpha**\n")
    (cmds / "mine.md").write_text("a command the user wrote\n")

    res = sync_mod._sync_claude_skills(tmp_path)
    out = tmp_path / ".claude" / "skills" / "alpha"
    text = (out / "SKILL.md").read_text()
    assert text.startswith("---\nname: alpha\ndescription: >\n  Do alpha things.")          # frontmatter first
    head = text.split("---\n", 2)[2]
    assert head.startswith(f"<!-- GENERATED by projio sync from pkg/alpha/SKILL.md; edit the source, not this copy -->\n")
    assert "# alpha" in text
    assert not os.access(out / "SKILL.md", os.W_OK) and not os.access(out / "notes.md", os.W_OK)
    assert (out / "notes.md").is_file() and (out / ".gitignore").read_text() == "*\n"
    assert json.loads((out / ".projio-skill").read_text())["origin"] == "package:x"
    assert (own / "SKILL.md").read_text().endswith("the project's own\n---\n")             # untouched
    assert res["written"] == ["alpha"] and res["kept"] == ["beta"]
    assert res["commands_removed"] == ["alpha"] and (cmds / "mine.md").is_file()

    assert sync_mod._sync_claude_skills(tmp_path)["action"] == "skipped"                   # up to date
    a.write_text(a.read_text().replace("Body.", "Body, changed."))
    assert sync_mod._sync_claude_skills(tmp_path)["written"] == ["alpha"]
    skills.pop(0)
    res = sync_mod._sync_claude_skills(tmp_path)
    assert res["removed"] == ["alpha"] and not out.exists()


def _setup(tmp_path, monkeypatch):
    src = tmp_path / ".projio" / "skills"
    a = _skill(src, "alpha", "Do alpha. Use for alpha.")
    skills = [{"name": "alpha", "path": ".projio/skills/alpha/SKILL.md", "source": "project"}]
    monkeypatch.setattr("projio.mcp.context._discover_skills", lambda root: list(skills))
    return a, skills


def test_header_names_project_source_relative(tmp_path, monkeypatch):
    _setup(tmp_path, monkeypatch)
    sync_mod._sync_claude_skills(tmp_path)
    text = (tmp_path / ".claude/skills/alpha/SKILL.md").read_text()
    assert "<!-- GENERATED by projio sync from .projio/skills/alpha/SKILL.md; edit the source" in text


def test_header_without_frontmatter_goes_on_top(tmp_path, monkeypatch):
    a, _ = _setup(tmp_path, monkeypatch)
    a.write_text("# alpha\n\nNo frontmatter.\n")
    sync_mod._sync_claude_skills(tmp_path)
    assert (tmp_path / ".claude/skills/alpha/SKILL.md").read_text().startswith("<!-- GENERATED by projio sync")


def test_check_reports_drift_and_sync_restores_edited_copy(tmp_path, monkeypatch):
    a, skills = _setup(tmp_path, monkeypatch)
    assert [d["status"] for d in sync_mod.check_skills(tmp_path)["drift"]] == ["missing"]
    sync_mod._sync_claude_skills(tmp_path)
    assert sync_mod.check_skills(tmp_path)["drift"] == []
    assert sync_mod.run_check(tmp_path) == 0

    copy = tmp_path / ".claude/skills/alpha/SKILL.md"
    copy.chmod(stat.S_IWUSR | stat.S_IRUSR)
    copy.write_text(copy.read_text() + "an agent's edit\n")
    assert [d["status"] for d in sync_mod.check_skills(tmp_path)["drift"]] == ["edited"]
    assert sync_mod.run_check(tmp_path) == 1

    res = sync_mod._sync_claude_skills(tmp_path)
    assert res["restored"] == ["alpha"]
    assert "an agent's edit" in (tmp_path / ".claude/skills/alpha.edited.md").read_text()
    assert "an agent's edit" not in copy.read_text()
    assert sync_mod.check_skills(tmp_path)["drift"] == []

    a.write_text(a.read_text() + "more\n")
    assert [d["status"] for d in sync_mod.check_skills(tmp_path)["drift"]] == ["stale"]
    skills.clear()
    assert [d["status"] for d in sync_mod.check_skills(tmp_path)["drift"]] == ["orphaned"]


def test_copies_from_an_older_sync_are_rewritten(tmp_path, monkeypatch):
    _setup(tmp_path, monkeypatch)
    sync_mod._sync_claude_skills(tmp_path)
    dest = tmp_path / ".claude/skills/alpha"
    stamp = json.loads((dest / ".projio-skill").read_text())
    stamp.pop("format")
    (dest / ".projio-skill").chmod(stat.S_IWUSR | stat.S_IRUSR)
    (dest / ".projio-skill").write_text(json.dumps(stamp))
    assert [d["status"] for d in sync_mod.check_skills(tmp_path)["drift"]] == ["outdated"]
    assert sync_mod._sync_claude_skills(tmp_path)["written"] == ["alpha"]
    assert sync_mod.check_skills(tmp_path)["drift"] == []


def _project(tmp_path, monkeypatch, body: str, config: str = ""):
    src = tmp_path / ".projio" / "skills"
    d = src / "flow"
    d.mkdir(parents=True)
    (d / "SKILL.md").write_text(f"---\nname: flow\ndescription: x\n---\n\n{body}")
    (tmp_path / ".projio" / "config.yml").write_text(config)
    monkeypatch.setattr("projio.mcp.context._discover_skills",
                        lambda root: [{"name": "flow", "path": ".projio/skills/flow/SKILL.md", "source": "project"}])


def test_lint_flags_conda_in_a_pixi_project(tmp_path, monkeypatch):
    _project(tmp_path, monkeypatch, "Run `conda run -n cogpy snakemake`.\nOr `pixi run snakemake`.\n")
    (tmp_path / "pixi.toml").write_text("[workspace]\nname = 'x'\n")
    res = sync_mod.lint_skills(tmp_path)
    assert res["runner"] == "pixi"
    assert [(f["line"], f["rule"]) for f in res["findings"]] == [(6, "env-manager")]
    assert res["findings"][0]["path"] == ".projio/skills/flow/SKILL.md"


def test_lint_flags_pixi_in_a_conda_project_and_honours_ignore(tmp_path, monkeypatch):
    _project(tmp_path, monkeypatch,
             "pixi run marimo edit nb.py\nconda run -n env x\npixi run y <!-- projio-lint: ignore -->\n",
             config="code:\n  runner: conda\n")
    res = sync_mod.lint_skills(tmp_path)
    assert res["runner"] == "conda" and [f["line"] for f in res["findings"]] == [6]


def test_lint_flags_retired_names_and_project_extras(tmp_path, monkeypatch):
    _project(tmp_path, monkeypatch, "Import notebook_bootstrap.\nUse old_helper.\nFine.\n",
             config="code:\n  runner: none\nskills:\n  lint:\n    retired: [old_helper]\n")
    found = sync_mod.lint_skills(tmp_path)["findings"]
    assert [(f["line"], f["rule"]) for f in found] == [(6, "retired"), (7, "retired")]


def test_lint_reads_the_projects_own_claude_skills(tmp_path, monkeypatch):
    _project(tmp_path, monkeypatch, "clean\n", config="code:\n  runner: pixi\n")
    own = tmp_path / ".claude" / "skills" / "mine"
    own.mkdir(parents=True)
    (own / "SKILL.md").write_text("---\nname: mine\ndescription: y\n---\nconda activate base\n")
    found = sync_mod.lint_skills(tmp_path)["findings"]
    assert [(f["skill"], f["line"]) for f in found] == [("mine", 5)]


def test_shipped_skills_do_not_restate_an_env_manager():
    """projio's own skills read the runner from runtime_conventions(); they name none."""
    bundled = Path(sync_mod.__file__).parent / "data" / "skills"
    hits = [f"{p.parent.name}:{n}" for p in sorted(bundled.glob("*/SKILL.md"))
            for n, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1)
            if sync_mod._LINT_IGNORE not in line
            and any(rx.search(line) for rx in sync_mod._RUNNER_COMMANDS.values())
            or any(t in line for t in sync_mod._RETIRED_TERMS)]
    assert hits == []


def test_run_check_exit_code_includes_lint(tmp_path, monkeypatch):
    _project(tmp_path, monkeypatch, "conda run -n e x\n", config="code:\n  runner: pixi\n")
    sync_mod._sync_claude_skills(tmp_path)
